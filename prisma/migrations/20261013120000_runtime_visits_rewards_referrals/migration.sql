-- The runtime half of the onboarding programme: the visits a reward can be redeemed
-- against, the rewards issued to members, and who referred whom.
--
-- PaidVisit exists because the implementation guide makes redemption conditional on a
-- payment or a consumed prepaid session, and says the backend — not staff convention —
-- must enforce it. It is deliberately source-agnostic: how a payment reaches Voone is an
-- open question in the guide, so `source` records the channel and the rule only cares that
-- the row exists. Only STAFF_ENTRY is accepted anywhere today.
--
-- PaidVisit holds amounts and counts, never what was bought. Treatment names are treated
-- as special-category data in this product (see PointsTransaction), and a financial record
-- that must be kept cannot also be erasable.
--
-- MemberReward is unique on (memberId, sourceKey), which is the idempotency key for
-- issuing: a retried visit cannot hand the same reward out twice.
--
-- Referral.referredId is unique, so a person can be recommended exactly once and a rival
-- referral cannot take the credit.
--
-- Generated by `prisma migrate diff` against the migrated database. That diff also wanted
-- to rename two PassDeviceRegistration indexes; that is drift that predates this change,
-- confirmed on a clean checkout, and is left alone rather than folded into an unrelated
-- migration.

